@pytest.mark.native
@pytest.mark.parametrize(
    "operation",
    (
        "t2v",
        "i2v",
        "flf",
        "klein_t2i",
        "klein_two_image",
        "wan_t2v",
        "wan_i2v",
        "wan_flf",
    ),
)
def test_user_and_builtin_reach_identical_native_boundaries(
    tmp_path, monkeypatch, operation
):
    from latentslate_engine import service
    from latentslate_engine.klein9b import two_image
    from latentslate_engine.klein9b.runtime import Klein9BRuntime
    from latentslate_engine.ltx23 import flf, i2v, t2v
    from latentslate_engine.wan2214b import flf as wan_flf
    from latentslate_engine.wan2214b import i2v as wan_i2v
    from latentslate_engine.wan2214b import pipeline

    ltx_paths = service.LtxModelPaths.from_home(tmp_path)
    klein_paths = service.KleinModelPaths.from_home(tmp_path)
    wan_paths = service.WanModelPaths.from_root(tmp_path / "wan")
    documents = builtin_documents(ltx_paths, klein_paths, wan_paths)
    document = next(
        doc
        for doc in documents.values()
        if service.TOOL_OPERATIONS[service.RECIPE_TO_BUILTIN[doc["operation"]]]
        == operation
    )
    _materialize(document, tmp_path)
    definition = compile_document(document)
    inputs = {
        item["key"]: item["default"]
        for item in definition.surface()
        if "default" in item
    }
    inputs["prompt"] = "A forest clearing"
    for item in definition.surface():
        if item["type"] == "image":
            path = tmp_path / (item["key"] + ".png")
            path.write_bytes(_png(inputs["width"], inputs["height"]))
            inputs[item["key"]] = path
    observed = []

    class LtxBoundary:
        def __init__(self, identity):
            self.identity = identity
            observed.append(("identity", identity))

        def close(self):
            pass

        def generate(self, *, progress=None, **request):
            observed.append(("request", request))
            return SimpleNamespace(save_mp4=lambda path: path.write_bytes(b"boundary"))

    if operation in {"t2v", "i2v", "flf"}:
        module, class_name = {
            "t2v": (t2v, "Ltx23T2VRuntime"),
            "i2v": (i2v, "Ltx23I2VRuntime"),
            "flf": (flf, "Ltx23FlfRuntime"),
        }[operation]
        monkeypatch.setattr(module, class_name, LtxBoundary)

    class KleinBoundary:
        def __init__(self):
            self.identity = None

        ensure_identity = Klein9BRuntime.ensure_identity

        def close(self):
            self.identity = None

        def generate(self, *, identity, output, progress=None, **request):
            self.ensure_identity(identity)
            observed.extend((("identity", identity), ("request", request)))
            output.write_bytes(b"boundary")
            return SimpleNamespace(
                models_reused=False, conditioning_reused=False, reference_reused=False
            )

        generate_two_image = generate

    monkeypatch.setattr(two_image, "Klein9BTwoImageRuntime", KleinBoundary)

    class WanBoundary:
        def __init__(self, recipe, device="cpu"):
            self.recipe = recipe
            self.identity = recipe.identity
            self.device = device
            self._conditioning = self._conditioning_key = None
            self._image_conditioning = self._flf_conditioning = None
            observed.append(("identity", self.identity))

        def destroy(self):
            pass

        def generate(self, *, output_path, progress=None, **request):
            observed.append(("request", request))
            output_path.write_bytes(b"boundary")
            return SimpleNamespace(timings={})

    if operation.startswith("wan_"):
        module, class_name = {
            "wan_t2v": (pipeline, "WanSession"),
            "wan_i2v": (wan_i2v, "WanI2VSession"),
            "wan_flf": (wan_flf, "WanFLFSession"),
        }[operation]
        WanBoundary.replaced = getattr(module, class_name).replaced
        monkeypatch.setattr(module, class_name, WanBoundary)

    def execute(user_document):
        observed.clear()
        request_inputs = definition.resolve(inputs) if user_document else inputs
        messages = iter(
            [
                {
                    "type": "generate",
                    "operation": operation,
                    "inputs": request_inputs,
                    "output_path": tmp_path / "output.bin",
                    "recipe": user_document,
                },
                {"type": "close"},
            ]
        )
        replies = []
        connection = SimpleNamespace(
            recv=lambda: next(messages), send=replies.append, close=lambda: None
        )
        if operation.startswith("wan_"):
            service._wan_worker_main(wan_paths, connection)
        elif operation.startswith("klein_"):
            service._klein_worker_main(klein_paths, connection)
        else:
            service._ltx_worker_main(operation, ltx_paths, connection)
        assert replies[-1]["ok"] is True, replies
        return list(observed)

    builtin_boundary = execute(None)
    user_document = deepcopy(document)
    user_document["id"] = str(uuid4())
    user_document["name"] = "User copy"
    assert execute(user_document) == builtin_boundary
    assert [kind for kind, _ in builtin_boundary] == ["identity", "request"]
