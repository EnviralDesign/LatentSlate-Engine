class RecipeRuntime(FakeRuntime):
    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.recipes = []

    def generate(self, operation, inputs, output_path, progress=None, *, recipe=None):
        self.recipes.append(recipe)
        assert recipe is not None
        recipe = compile_document(recipe)
        assert (
            recipe.resolve(
                {item["key"]: inputs[item["key"]] for item in recipe.surface()}
            )
            == inputs
        )
        super().generate(operation, inputs, output_path, progress)


def _payload(client, tool):
    inputs = {
        item["key"]: item["default"] for item in tool["inputs"] if "default" in item
    }
    inputs["prompt"] = "A forest clearing"
    for item in tool["inputs"]:
        if item["type"] == "image":
            width = tool["canvas"].get("fixed_width", inputs.get("width")) or 256
            height = tool["canvas"].get("fixed_height", inputs.get("height")) or 256
            asset = client.post(
                "/v1/assets",
                files={
                    "file": (
                        "source.png",
                        _png(width, height),
                        "image/png",
                    )
                },
            ).json()
            inputs[item["key"]] = {"type": "asset", "asset_id": asset["id"]}
    return {
        "tool_id": tool["id"],
        "schema_revision": tool["schema_revision"],
        "schema_hash": tool["schema_hash"],
        "recipe": tool["recipe"],
        "inputs": inputs,
    }


def _finished(client, job_id):
    deadline = time.monotonic() + 5
    while time.monotonic() < deadline:
        job = client.get(f"/v1/jobs/{job_id}").json()
        if job["status"] not in {"queued", "running"}:
            return job
        time.sleep(0.01)
    raise AssertionError("Job did not complete")


def test_all_eight_publish_execute_and_preserve_builtins(tmp_path):
    runtime = RecipeRuntime()
    with TestClient(create_app(home=tmp_path, token="", executor=runtime)) as client:
        builtins = client.get("/v1/catalog").json()["tools"]
        definitions = client.get("/v1/authoring/builtins").json()["recipes"]
        ids = []
        for builtin in definitions:
            record = client.post(
                f"/v1/authoring/builtins/{builtin['key']}/duplicate", json={}
            ).json()
            recipe_id = record["document"]["id"]
            path = f"/v1/authoring/recipes/{recipe_id}/publication"
            assert client.get(path).json()["enabled"] is False
            _materialize(record["document"], tmp_path)
            response = client.put(path, json={"enabled": True})
            assert response.status_code == 200, response.text
            tool = response.json()["tool"]
            assert tool["available"] is True
            assert tool["schema_revision"] == 1
            ids.append(tool["id"])
            payload = _payload(client, tool)
            malformed = deepcopy(payload)
            malformed["recipe"]["revision"] = True
            assert client.post("/v1/jobs", json=malformed).status_code == 409
            accepted = client.post("/v1/jobs", json=payload)
            assert accepted.status_code == 200, accepted.text
            result = _finished(client, accepted.json()["id"])
            assert result["status"] == "succeeded", result
            assert result["recipe"] == tool["recipe"]
            assert result["tool_id"] == tool["id"]
        catalog = client.get("/v1/catalog").json()["tools"]
        assert catalog[:8] == builtins
        assert len(set(ids)) == 8
        assert len(catalog) == 16
        assert len(runtime.recipes) == 8
    with TestClient(
        create_app(home=tmp_path, token="", executor=RecipeRuntime())
    ) as client:
        assert {
            item["id"] for item in client.get("/v1/catalog").json()["tools"][8:]
        } == set(ids)


def test_queued_revision_survives_edit_disable_and_rejects_stale_requests(tmp_path):
    runtime = RecipeRuntime(blocked=True)
    with TestClient(create_app(home=tmp_path, token="", executor=runtime)) as client:
        record = client.post(
            "/v1/authoring/builtins/ltx23.t2v.v1/duplicate", json={}
        ).json()
        _materialize(record["document"], tmp_path)
        recipe_id = record["document"]["id"]
        path = f"/v1/authoring/recipes/{recipe_id}"
        tool = client.put(path + "/publication", json={"enabled": True}).json()["tool"]
        payload = _payload(client, tool)
        first = client.post("/v1/jobs", json=payload).json()
        assert runtime.started.wait(2)
        queued = client.post("/v1/jobs", json=payload).json()
        document = deepcopy(record["document"])
        _field(document, "seed")["value"] = 99
        updated = client.put(path, json={"base_revision": 1, "document": document})
        assert updated.status_code == 200
        assert client.post("/v1/jobs", json=payload).status_code == 409
        latest = client.get(path + "/publication").json()["tool"]
        stale_recipe = _payload(client, latest)
        stale_recipe["recipe"] = tool["recipe"]
        assert client.post("/v1/jobs", json=stale_recipe).status_code == 409
        client.put(path + "/publication", json={"enabled": False})
        assert client.post("/v1/jobs", json=_payload(client, latest)).status_code == 422
        runtime.finish.set()
        for job in (first, queued):
            result = _finished(client, job["id"])
            assert result["status"] == "succeeded"
            assert result["recipe"] == tool["recipe"]
        assert all(
            inputs["seed"] == payload["inputs"]["seed"] for inputs in runtime.inputs
        )


def test_hidden_revision_freshness_stable_identity_and_cross_host_import(tmp_path):
    with TestClient(
        create_app(home=tmp_path / "source", token="", executor=RecipeRuntime())
    ) as client:
        record = client.post(
            "/v1/authoring/builtins/ltx23.t2v.v1/duplicate", json={}
        ).json()
        recipe_id = record["document"]["id"]
        path = f"/v1/authoring/recipes/{recipe_id}"
        # Editing before the first publication does not consume schema revisions.
        document = record["document"]
        _field(document, "seed")["value"] = 123
        record = client.put(
            path, json={"base_revision": 1, "document": document}
        ).json()
        assert "schema" not in record and "enabled" not in record
        _materialize(document, tmp_path)
        original = client.put(path + "/publication", json={"enabled": True}).json()[
            "tool"
        ]
        assert original["schema_revision"] == 1
        old_payload = _payload(client, original)
        document["name"] = "Renamed user recipe"
        _field(document, "transformer_adapter_strengths")["value"] = [0.25]
        updated = client.put(path, json={"base_revision": 2, "document": document})
        assert updated.status_code == 200, updated.text
        latest = client.get(path + "/publication").json()["tool"]
        assert latest["id"] == original["id"] and latest["key"] == original["key"]
        assert latest["schema_hash"] == original["schema_hash"]
        assert latest["schema_revision"] == 1
        assert latest["recipe"]["revision"] == 3
        assert (
            latest["recipe"]["definition_hash"] != original["recipe"]["definition_hash"]
        )
