def test_production_projection_matches_frozen_inputs_and_schema(probe) -> None:
    tool_id, definition = probe
    expected = next(tool for tool in _baseline() if tool["id"] == tool_id)
    surface = definition.surface()
    projected = catalog.TOOLS_BY_ID[tool_id]["inputs"]
    assert projected == expected["inputs"]
    assert [item["key"] for item in surface] == [
        item["key"] for item in expected["inputs"]
    ]
    assert all(
        not item.get("nullable") and not item.get("collection") for item in surface
    )
    assert all("label" not in item and "ui" not in item for item in surface)
    assert all(item["type"] not in {"artifact", "adapter"} for item in surface)
    exposed_keys = {
        field.capability.key for field in definition.fields if field.exposed
    }
    hidden_keys = {
        cap.key for cap in definition.capabilities.capabilities
    } - exposed_keys
    assert not hidden_keys & {item["key"] for item in projected}

    # Tool identity, canvas, timing and hashing stay on the catalog side.
    tool = catalog.TOOLS_BY_ID[tool_id]
    base = {
        key: value
        for key, value in tool.items()
        if key not in {"schema_hash", "timing"}
    }
    assert tool == expected
    assert catalog._schema_hash(base) == expected["schema_hash"]
    assert (
        catalog._schema_hash({**base, "timing": tool["timing"]})
        != expected["schema_hash"]
    )


def test_semantics_feed_production_but_presentation_is_service_owned(
    probe, monkeypatch
) -> None:
    tool_id, definition = probe
    changed = replace(
        definition,
        fields=tuple(
            exposed(field.capability, default="Recipe prompt")
            if field.capability.key == "prompt"
            else exposed(field.capability, default=3.0, minimum=2.0, maximum=4.0)
            if field.capability.key == "duration_seconds"
            else field
            for field in reversed(definition.fields)
        ),
    )
    monkeypatch.setattr(catalog, PROBES[tool_id], changed)
    tools = catalog._tool_definitions()
    tool = next(item for item in tools if item["id"] == tool_id)
    assert [item["key"] for item in tool["inputs"]] == [
        item["key"] for item in changed.surface()
    ]
    projected = {item["key"]: item for item in tool["inputs"]}
    assert projected["prompt"]["default"] == "Recipe prompt"
    assert projected["prompt"]["required"] is False
    assert projected["duration_seconds"]["default"] == 3.0
    assert projected["duration_seconds"]["ui"] == {
        "min": 2.0,
        "max": 4.0,
        "step": 0.5
        if tool_id in {catalog.T2V_ID, catalog.I2V_ID, catalog.FLF_ID}
        else 0.25,
        "unit": "seconds",
    }
    for semantic, public in zip(changed.surface(), projected.values(), strict=True):
        assert public["key"] == semantic["key"]
        assert public["type"] == semantic["type"]
        assert public.get("role") == semantic.get("role")
        assert public.get("default") == semantic.get("default")
    surface = {item["key"]: item for item in definition.surface()}
    assert surface["seed"]["constraints"] == {"min": 0, "max": 2**64 - 1}
    assert "ui" not in projected["seed"]
    assert "max" in surface["width"]["constraints"]
    assert set(projected["width"]["ui"]) == {"min", "step"}

    baseline = next(item for item in _baseline() if item["id"] == tool_id)
    assert {
        key: value
        for key, value in tool.items()
        if key not in {"inputs", "schema_hash"}
    } == {
        key: value
        for key, value in baseline.items()
        if key not in {"inputs", "schema_hash"}
    }
    assert [item for item in tools if item["id"] != tool_id] == [
        item for item in _baseline() if item["id"] != tool_id
    ]
    assert projected["prompt"]["ui"] == {
        "multiline": True,
        "placeholder": "Describe the shot",
    }
    for item in baseline["inputs"]:
        assert projected[item["key"]]["label"] == item["label"]
    assert all(
        projected[key]["required"] is True
        for key in ("width", "height", "duration_seconds", "seed")
    )
    assert catalog.TOOLS == _baseline()


